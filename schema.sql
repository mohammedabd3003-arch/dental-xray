create or replace function public.app_role() returns text
language sql stable security definer set search_path = public as $$
  select coalesce((select role from public.staff_profiles where id = auth.uid() and active), 'none')
$$;

create or replace function public.in_group(g text) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.staff_groups where staff_id = auth.uid() and group_id = g)
$$;

create or replace function public.can_read_group(g text) returns boolean
language sql stable security definer set search_path = public as $$
  select case public.app_role()
           when 'admin' then true
           when 'ro'    then true
           when 'ins'   then public.in_group(g)
           when 'lab'   then public.in_group(g)
           else false end
$$;

create or replace function public.can_write_group(g text, roles text[]) returns boolean
language sql stable security definer set search_path = public as $$
  select public.app_role() = 'admin' or (public.app_role() = any(roles) and public.in_group(g))
$$;

create or replace function public.student_group(s text) returns text
language sql stable security definer set search_path = public as $$
  select group_id from public.students where id = s
$$;

create or replace function public.session_group(s text) returns text
language sql stable security definer set search_path = public as $$
  select group_id from public.sessions where id = s
$$;

-- المدرس: كل حقول الدرجات لكروباته · مساعد المختبر: التقييم العملي والملاحظات فقط
create or replace function public.can_score(s text, f text) returns boolean
language sql stable security definer set search_path = public as $$
  select public.app_role() = 'admin'
      or (public.in_group(public.student_group(s))
          and (public.app_role() = 'ins' or (public.app_role() = 'lab' and f in ('prac','note'))))
$$;

create or replace function public.app_schema_version() returns text
language sql immutable as $$ select '2.0' $$;
grant execute on function public.app_schema_version() to authenticated;

-- ---------------------------------------------------------------------
-- 4) ترحيل بيانات النسخة القديمة (السجل الواحد lab_state) إن وُجدت
-- ---------------------------------------------------------------------
do $$
declare s jsonb;
begin
  if to_regclass('public.lab_state') is null then return; end if;
  execute 'select state_data from public.lab_state where id = ''main''' into s;
  if s is null then return; end if;

  insert into public.groups (id, name, sort)
    select g->>'id', coalesce(nullif(g->>'name',''), g->>'id'), (o - 1)::int
    from jsonb_array_elements(coalesce(s->'groups','[]'::jsonb)) with ordinality as t(g, o)
    where coalesce(g->>'id','') <> ''
  on conflict (id) do nothing;

  insert into public.students (id, name, group_id, demo)
    select x->>'id', left(x->>'name', 200), x->>'gid', coalesce((x->>'demo')::boolean, false)
    from jsonb_array_elements(coalesce(s->'students','[]'::jsonb)) with ordinality as t(x, o)
    where coalesce(x->>'id','') <> '' and length(coalesce(x->>'name','')) > 0
      and exists (select 1 from public.groups g where g.id = x->>'gid')
    order by o
  on conflict (id) do nothing;

  insert into public.sessions (id, group_id, session_date, demo)
    select x->>'id', x->>'gid', (x->>'date')::date, coalesce((x->>'demo')::boolean, false)
    from jsonb_array_elements(coalesce(s->'sessions','[]'::jsonb)) as t(x)
    where coalesce(x->>'id','') <> '' and coalesce(x->>'date','') ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'
      and exists (select 1 from public.groups g where g.id = x->>'gid')
  on conflict (id) do nothing;

  insert into public.attendance (session_id, student_id, status)
    select x->>'id', a.key, a.value
    from jsonb_array_elements(coalesce(s->'sessions','[]'::jsonb)) as t(x),
         jsonb_each_text(case when jsonb_typeof(x->'a') = 'object' then x->'a' else '{}'::jsonb end) as a
    where a.value in ('p','a','e')
      and exists (select 1 from public.sessions z where z.id = x->>'id')
      and exists (select 1 from public.students z where z.id = a.key)
  on conflict do nothing;

  insert into public.scores (student_id, field, value)
    select c.key, f.k, c.value->>f.k
    from jsonb_each(case when jsonb_typeof(s->'sc') = 'object' then s->'sc' else '{}'::jsonb end) as c
    cross join (values ('prac'),('exam'),('act'),('note')) as f(k)
    where jsonb_typeof(c.value) = 'object'
      and exists (select 1 from public.students z where z.id = c.key)
      and coalesce(c.value->>f.k, '') <> ''
      and case when f.k = 'note' then length(c.value->>f.k) <= 2000
               when (c.value->>f.k) ~ '^[0-9]+(\.[0-9]+)?$' then (c.value->>f.k)::numeric between 0 and 100
               else false end
  on conflict do nothing;

  insert into public.scores (student_id, field, value)
    select c.key, 'w' || w.key, w.value
    from jsonb_each(case when jsonb_typeof(s->'sc') = 'object' then s->'sc' else '{}'::jsonb end) as c,
         jsonb_each_text(case when jsonb_typeof(c.value) = 'object' and jsonb_typeof(c.value->'w') = 'object'
                              then c.value->'w' else '{}'::jsonb end) as w
    where exists (select 1 from public.students z where z.id = c.key)
      and w.key ~ '^[0-9]{1,2}$'
      and case when w.value ~ '^[0-9]+(\.[0-9]+)?$' then w.value::numeric between 0 and 100 else false end
  on conflict do nothing;

  if jsonb_typeof(s->'cfg') = 'object' then
    insert into public.app_settings (id, cfg) values ('main', s->'cfg')
    on conflict (id) do update set cfg = excluded.cfg;
  end if;

  update public.xray_records r
     set annotations = case when jsonb_typeof(i->'ann') = 'array' then i->'ann' else '[]'::jsonb end
    from jsonb_array_elements(coalesce(s->'imgs','[]'::jsonb)) as t(i)
   where r.id = i->>'id';

  raise notice 'تم ترحيل بيانات lab_state';
end $$;

