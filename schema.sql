create or replace function public.touch_row() returns trigger
language plpgsql as $$
begin
  new.updated_at := now();
  new.updated_by := auth.uid();
  return new;
end $$;

create or replace function public.audit_row() returns trigger
language plpgsql security definer set search_path = public as $$
declare o jsonb; n jsonb;
begin
  if tg_op <> 'INSERT' then o := to_jsonb(old) - 'updated_at' - 'updated_by'; end if;
  if tg_op <> 'DELETE' then n := to_jsonb(new) - 'updated_at' - 'updated_by'; end if;
  if tg_op = 'UPDATE' and o = n then return null; end if;
  insert into public.audit_log (actor, actor_name, tbl, op, old_data, new_data)
  values (auth.uid(),
          (select coalesce(full_name, email) from public.staff_profiles where id = auth.uid()),
          tg_table_name, tg_op, o, n);
  return null;
end $$;

do $$
declare t text;
begin
  foreach t in array array['groups','students','sessions','attendance','scores','app_settings','xray_records'] loop
    execute format('drop trigger if exists trg_touch on public.%I', t);
    execute format('create trigger trg_touch before insert or update on public.%I for each row execute function public.touch_row()', t);
  end loop;
  foreach t in array array['groups','students','sessions','attendance','scores','app_settings','xray_records','staff_profiles','staff_groups'] loop
    execute format('drop trigger if exists trg_audit on public.%I', t);
    execute format('create trigger trg_audit after insert or update or delete on public.%I for each row execute function public.audit_row()', t);
  end loop;
end $$;

-- كل حساب جديد يُنشأ معطّلاً بصلاحية «قراءة فقط» حتى يفعّله المدير
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.staff_profiles (id, email, full_name, role, active)
  values (new.id, new.email, split_part(new.email, '@', 1), 'ro', false)
  on conflict (id) do nothing;
  return new;
end $$;
drop trigger if exists on_auth_user_created_dentlab on auth.users;
create trigger on_auth_user_created_dentlab after insert on auth.users
  for each row execute function public.handle_new_user();

